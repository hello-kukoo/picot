#!/usr/bin/env node
// ABOUTME: Deterministic Gate R recovery-rehearsal matrix generator.
// ABOUTME: Records unexecuted real-release evidence without claiming a rehearsal passed.

import { mkdir, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";

const REAL_RELEASE_STATUS = "UNEXECUTED_REAL_RELEASE_EVIDENCE";

const cases = [
  ["R-01", "fresh DB", "Open empty metadata DB; expect schema v3 and zero registry rows."],
  [
    "R-02",
    "old DB upgrade",
    "Open v0/v1/v2 fixture; expect staircase migration, unknown tables and rows preserved.",
  ],
  [
    "R-03",
    "schema mismatch / N-1 refusal",
    "Detect v3 before automatic upgrade; N-1 must refuse startup and leave DB untouched.",
  ],
  [
    "R-04",
    "verified pre-upgrade backup",
    "Create backup before upgrade; verify byte/hash/readability before mutating source DB.",
  ],
  [
    "R-05",
    "version-matched controlled restore/downgrade",
    "Use shipped version-matched restore tool; never use git checkout or source rollback.",
  ],
  [
    "R-06",
    "missing workspace",
    "Resolve absent workspace ID as stable not_registered; show remediation without inventing root authority.",
  ],
  [
    "R-07",
    "missing directory",
    "Prune vanished registered directory DB row only; preserve workspace/session files outside registry operation.",
  ],
  [
    "R-08",
    "unregistered default ~/.pi/tmp",
    "Keep default startup root Temporary/live-only; no add/touch registry row and no synthetic workspace ID.",
  ],
  [
    "R-09",
    "Quick Chat tokenized child lifecycle",
    "Create 0700 token child under tmp; close/replacement cleans only owned child.",
  ],
  [
    "R-10",
    "root-delete / symlink guard",
    "Reject deleted or symlinked temporary root/child; never follow outside approved tmp root.",
  ],
  [
    "R-11",
    "cleanup failure / recovery",
    "Surface cleanup failure, retain recovery metadata, retry safely without deleting unrelated paths.",
  ],
  [
    "R-12",
    "session-file preservation",
    "Restore registry DB without deleting or rewriting Pi session JSONL files.",
  ],
  [
    "R-13",
    "running runtime disposition",
    "Record running runtime policy; drain/restart explicitly, never silently claim it was recovered.",
  ],
  [
    "R-14",
    "static cache",
    "Verify downgraded artifact invalidates incompatible static cache and loads matching assets.",
  ],
  [
    "R-15",
    "user remediation",
    "Show actionable backup/restore, missing-directory and runtime restart guidance on each failure.",
  ],
];

function buildReport() {
  return {
    rehearsal: "gate-r-recovery",
    contract: "native-runtime-migration §13.2 / WP-R.5",
    evidenceStatus: REAL_RELEASE_STATUS,
    executionPolicy: {
      realReleaseRun: false,
      reason:
        "This harness is deterministic planning/evidence tooling; it does not mutate a user DB, launch a release artifact, or imply macOS/Windows evidence.",
      forbiddenRollback: "git checkout/tag/source revert",
      requiredRollback: "version-matched controlled restore/downgrade tool",
    },
    cases: cases.map(([id, scenario, expected]) => ({
      id,
      scenario,
      expected,
      status: REAL_RELEASE_STATUS,
      evidence: "not recorded",
    })),
    gateR: {
      canClose: false,
      blocker:
        "Real N-1 → N → N-1 release rehearsal and platform artifact evidence are not recorded.",
    },
  };
}

function markdown(report) {
  const lines = [
    "# Gate R recovery rehearsal report",
    "",
    `Evidence status: **${report.evidenceStatus}**`,
    "",
    "> Generated by `bun run rehearsal:recovery`. This report deliberately does not claim a real release rehearsal passed.",
    "",
    "## Matrix",
    "",
    "| ID | Scenario | Expected result | Real-release evidence |",
    "| --- | --- | --- | --- |",
  ];
  for (const item of report.cases) {
    lines.push(`| ${item.id} | ${item.scenario} | ${item.expected} | **${item.status}** |`);
  }
  lines.push(
    "",
    "## Execution boundary",
    "",
    `- Real release run: **${report.executionPolicy.realReleaseRun ? "yes" : "no"}**.`,
    `- Reason: ${report.executionPolicy.reason}`,
    `- Forbidden rollback: \`${report.executionPolicy.forbiddenRollback}\`.`,
    `- Required rollback: ${report.executionPolicy.requiredRollback}.`,
    "- A future run must use isolated copies of a real release artifact, DB backup, session tree and cache; record commands, hashes, versions, platform, runtime disposition and user-visible remediation.",
    "",
    "## Gate decision",
    "",
    `- Gate R closure: **cannot close** — ${report.gateR.blocker}`,
    "- This output is a deterministic harness/matrix, not substitute evidence.",
    "",
  );
  return lines.join("\n");
}

async function main() {
  const args = process.argv.slice(2);
  const json = buildReport();
  if (args.includes("--check")) {
    if (
      json.cases.length !== 15 ||
      json.cases.some((item) => item.status !== REAL_RELEASE_STATUS)
    ) {
      throw new Error("recovery rehearsal matrix is incomplete or falsely marked");
    }
    process.stdout.write(`validated ${json.cases.length} cases; ${REAL_RELEASE_STATUS}\n`);
    return;
  }
  const outIndex = args.indexOf("--out");
  if (outIndex !== -1) {
    const output = resolve(
      args[outIndex + 1] ??
        "docs/superpowers/specs/2026-08-28-registry-runtime-recovery-rehearsal.md",
    );
    await mkdir(dirname(output), { recursive: true });
    await writeFile(output, markdown(json));
    process.stdout.write(`${output}\n`);
    return;
  }
  process.stdout.write(`${JSON.stringify(json, null, 2)}\n`);
}

await main();
