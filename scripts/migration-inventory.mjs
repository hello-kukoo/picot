// ABOUTME: Extracts legacy runtime routes, commands, and production callers into a deterministic migration inventory.
// ABOUTME: Generates both a reviewable Markdown matrix and machine-readable JSON without importing production modules.

import { mkdir, readFile, writeFile } from "node:fs/promises";
import { relative, resolve } from "node:path";

const root = resolve(import.meta.dirname, "..");
const embeddedPath = resolve(root, "extensions/embedded-server.ts");
const embedded = await readFile(embeddedPath, "utf8");

function unique(values) {
  return [...new Set(values)].sort();
}

const routes = [];
for (const match of embedded.matchAll(
  /urlPath\.startsWith\((['"`])([^'"`]+)\1\)|urlPath\s*===\s*(['"`])([^'"`]+)\3/g,
)) {
  const path = match[2] ?? match[4];
  if (path.startsWith("/api/") || path === "/ws") routes.push(path);
}
const commands = unique(
  [...embedded.matchAll(/case\s+["']([A-Za-z0-9_]+)["']\s*:/g)].map((m) => m[1]),
);
const apiRoutes = unique(routes);

const files = [];
for (const directory of ["public", "extensions", "tests"]) {
  const glob = new Bun.Glob(`${directory}/**/*.{js,ts,html,mjs}`);
  for await (const file of glob.scan({ cwd: root, onlyFiles: true })) files.push(file);
}
const callers = [];
for (const file of files.sort()) {
  const source = await readFile(resolve(root, file), "utf8");
  for (const [lineNumber, line] of source.split("\n").entries()) {
    if (/\bfetch\s*\(|\bsendControl\s*\(|\bpostRpc\s*\(|\bbroker_control\b/.test(line)) {
      callers.push({
        id: `${file}:${lineNumber + 1}`,
        file,
        line: lineNumber + 1,
        text: line.trim(),
      });
    }
  }
}

const brokerSource = await readFile(resolve(root, "src-tauri/src/broker_ws.rs"), "utf8");
const routerSource = await readFile(resolve(root, "src-tauri/src/host_router.rs"), "utf8");
const controls = unique(
  [
    ...brokerSource.matchAll(
      /(?:command|control_type|action|type)\s*==\s*["']([A-Za-z0-9_.-]+)["']/g,
    ),
  ].map((m) => m[1]),
);
const hostFrames = unique(
  [
    ...routerSource.matchAll(
      /["'](runtime_[a-z_]+|host_[a-z_]+|hello(?:_ack)?|error|response|event|snapshot)["']/g,
    ),
  ].map((m) => m[1]),
);

const inventory = {
  version: 1,
  generatedBy: "scripts/migration-inventory.mjs",
  surfaces: {
    embeddedHttp: apiRoutes,
    embeddedCommands: commands,
    websocket: ["/ws", "browser connection", "extension_ui_response", "OAuth commands"],
    brokerControls: controls,
    hostFrames,
  },
  callers,
  counts: {
    embeddedHttp: apiRoutes.length,
    embeddedCommands: commands.length,
    callers: callers.length,
    brokerControls: controls.length,
    hostFrames: hostFrames.length,
  },
};

const outputPath =
  process.env.MIGRATION_INVENTORY_OUTPUT ?? resolve(root, "scripts/gen/inventory.json");
// Generated report goes to gen/ only — the curated Gate A document under
// docs/ is human-maintained and must never be overwritten by the generator.
const docPath =
  process.env.MIGRATION_INVENTORY_DOC ?? resolve(root, "scripts/gen/inventory-report.md");
await mkdir(resolve(root, "scripts/gen"), { recursive: true });
await mkdir(resolve(root, "docs/superpowers/specs"), { recursive: true });
await writeFile(outputPath, `${JSON.stringify(inventory, null, 2)}\n`);
const lines = [
  "# Native Runtime Migration Inventory",
  "",
  "> Generated by `bun run migration:inventory`. Review callers and assign Gate A IDs before migration work.",
  "",
  `Generated counts: HTTP ${apiRoutes.length}, commands ${commands.length}, callers ${callers.length}, broker controls ${controls.length}, host frames ${hostFrames.length}.`,
  "",
  "## Embedded HTTP routes",
  "",
  ...apiRoutes.map((path, index) => `- A-HTTP-${String(index + 1).padStart(2, "0")} \`${path}\``),
  "",
  "## Embedded WebSocket commands",
  "",
  ...commands.map(
    (command, index) => `- A-WS-${String(index + 1).padStart(2, "0")} \`${command}\``,
  ),
  "",
  "## Broker controls and host frames",
  "",
  `- Broker controls: ${controls.map((value) => `\`${value}\``).join(", ") || "(none extracted; review dispatch_control manually)"}`,
  `- Host frames: ${hostFrames.map((value) => `\`${value}\``).join(", ") || "(none extracted; review host_router manually)"}`,
  "",
  "## Production callers",
  "",
  ...callers.map(
    (caller, index) =>
      `- A-CALLER-${String(index + 1).padStart(3, "0")} \`${caller.file}:${caller.line}\` — ${caller.text}`,
  ),
  "",
  "## Review notes",
  "",
  "- Extraction is syntax-oriented and intentionally does not decide migration ownership or deletion eligibility.",
  "- A-CALLER-NNN are sorted positions and drift on insertion; stable references use the caller `id` (`file:line`) field.",
  "- `startsWith` route matches are retained as normalized route prefixes; route counts are generated, not hard-coded.",
  "- Review `dispatch_control`, OAuth, extension UI, static assets, and binary/download paths against source before Gate A approval.",
];
await writeFile(docPath, `${lines.join("\n")}\n`);
console.log(`Wrote ${relative(root, outputPath)} and ${relative(root, docPath)}`);
